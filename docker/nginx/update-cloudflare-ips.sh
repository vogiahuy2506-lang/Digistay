#!/usr/bin/env bash
# Rewrites docker/nginx/conf.d/cloudflare-real-ip.inc from Cloudflare's
# published ranges (https://www.cloudflare.com/ips/). They change rarely;
# run this when Cloudflare announces a change, review the diff, commit:
# the deploy reloads nginx with it.
#
#   bash docker/nginx/update-cloudflare-ips.sh           rewrite the file
#   bash docker/nginx/update-cloudflare-ips.sh --check   only compare: exit 1 when out of date
#
# A Cloudflare range missing here means guests reaching us through it are
# all counted as that Cloudflare address by rate limits and lockouts.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
OUT=conf.d/cloudflare-real-ip.inc

v4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS https://www.cloudflare.com/ips-v6)"
# Refuse anything that is not a plain CIDR list (an error page, a proxy).
grep -Evq '^[0-9.]+/[0-9]+$' <<<"$v4" && { echo "unexpected ips-v4 content" >&2; exit 1; }
grep -Evq '^[0-9a-f:]+/[0-9]+$' <<<"$v6" && { echo "unexpected ips-v6 content" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  cat <<'HEAD'
# Real client IP behind Cloudflare (generated by docker/nginx/update-cloudflare-ips.sh).
#
# Only a connection FROM a Cloudflare range may name the client with
# CF-Connecting-IP; anyone else is taken at their own address. So this is
# harmless while digistay.vn is not proxied, and once it is, $remote_addr
# (sent to the app as X-Real-IP, read by getClientIp()) is the guest's IP
# instead of Cloudflare's: rate limits and lockouts keep working per person.
real_ip_header CF-Connecting-IP;
HEAD
  sed 's/^/set_real_ip_from /; s/$/;/' <<<"$v4"
  sed 's/^/set_real_ip_from /; s/$/;/' <<<"$v6"
} > "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  if cmp -s "$tmp" "$OUT"; then
    echo "$OUT is up to date ($(grep -c set_real_ip_from "$OUT") ranges)"
    exit 0
  fi
  echo "$OUT differs from Cloudflare's published ranges (< file, > Cloudflare):" >&2
  diff "$OUT" "$tmp" >&2 || true
  exit 1
fi
cat "$tmp" > "$OUT"
echo "wrote $OUT ($(grep -c set_real_ip_from "$OUT") ranges)"
